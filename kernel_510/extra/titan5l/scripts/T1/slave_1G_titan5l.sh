#! /bin/bash

# 88e6352-1: id=0

# set Physical Control Register of port 5
dsa_switch write 0 0x15 0x1 0x003e

# read phy chip id, expect 0x0983 for 88Q2112
# can be skipped
dsa_switch write 0 0x1c 0x19 0x0003
dsa_switch write 0 0x1c 0x18 0x80a1
dsa_switch write 0 0x1c 0x18 0x8ca1
dsa_switch read 0 0x1c 0x19 

# disable the Auto-Negotiation process
# can be skipped
dsa_switch write 0 0x1c 0x19 0x0200
dsa_switch write 0 0x1c 0x18 0x80a7
dsa_switch write 0 0x1c 0x19 0x0000
dsa_switch write 0 0x1c 0x18 0x84a7

# work as slave @ 1000M
dsa_switch write 0 0x1c 0x19 0x0834
dsa_switch write 0 0x1c 0x18 0x80a1
dsa_switch write 0 0x1c 0x19 0x8001
dsa_switch write 0 0x1c 0x18 0x84a1


